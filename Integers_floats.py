#integers
num1=1000
num2=20 

#Addition(+)
total=num1+num2
print(total)

#Subtraction(-)
total=num1-num2 
print(total)

#Multiplication(*)
total=num1*num2 
print(total)

#Division(/)
total=num1/num2
print(total)

#modulus(%) #prints the remainder of the division
x=11%2
print(x) 

#flooor operator(//) #prints the whole number of the division and ignores the remainder 
x=11//2
print(x) 

#exponentiation(**) #prints the power of the number
x=2**3
print(x) 

#floats
num4=995.567

#round() #rounds off the number to the nearest whole number or to the specified decimal places
num5=round(num4)
print(num5)
num6=round(num4,2)
print(num6)
num7=round(num4,1)
print(num7)


